upsert_statuses AS (
  INSERT INTO public.order_statuses (
    id,
    display_order,
    status_key,
    patient_status_label,
    patient_microcopy,
    patient_action_required,
    admin_status_label,
    admin_microcopy,
    next_step_owner,
    expiration_timer_hours,
    is_terminal,
    is_active,
    created_at,
    updated_at,
    is_patient_visible
  )
  SELECT
    ds.id,
    ds.display_order,
    ds.status_key,
    ds.patient_status_label,
    ds.patient_microcopy,
    ds.patient_action_required,
    ds.admin_status_label,
    ds.admin_microcopy,
    ds.next_step_owner,
    ds.expiration_timer_hours,
    ds.is_terminal,
    ds.is_active,
    ds.created_at,
    ds.updated_at,
    ds.is_patient_visible
  FROM desired_statuses ds
  ON CONFLICT (status_key) DO UPDATE
  SET
    display_order = EXCLUDED.display_order,
    patient_status_label = EXCLUDED.patient_status_label,
    patient_microcopy = EXCLUDED.patient_microcopy,
    patient_action_required = EXCLUDED.patient_action_required,
    admin_status_label = EXCLUDED.admin_status_label,
    admin_microcopy = EXCLUDED.admin_microcopy,
    next_step_owner = EXCLUDED.next_step_owner,
    expiration_timer_hours = EXCLUDED.expiration_timer_hours,
    is_terminal = EXCLUDED.is_terminal,
    is_active = EXCLUDED.is_active,
    is_patient_visible = EXCLUDED.is_patient_visible
  RETURNING id
),
max_desired_order AS (
  SELECT MAX(display_order) AS max_order
  FROM desired_statuses
),
legacy_statuses AS (
  SELECT
    os.id,
    ROW_NUMBER() OVER (ORDER BY os.display_order, os.status_key, os.id) AS row_num
  FROM public.order_statuses os
  WHERE os.status_key NOT IN (SELECT status_key FROM desired_statuses)
)
UPDATE public.order_statuses os
SET
  is_active = false,
  display_order = mdo.max_order + ls.row_num
FROM legacy_statuses ls
CROSS JOIN max_desired_order mdo
WHERE os.id = ls.id;
